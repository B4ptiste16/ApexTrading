"""
APEX · build-time version embedder  (v3.1.6+)
─────────────────────────────────────────────────────────────────────
Reads version.json from the project root, writes core/_version.py
with the version string baked in as a Python constant. PyInstaller
then bundles that .py the same way it bundles every other module —
no runtime file lookup, no sys._MEIPASS shenanigans, no possible
"v1.0.0" regression.

build.bat calls this script BEFORE PyInstaller. In dev mode
(`python main.py`) the embedded version is still picked up because
core/_version.py is committed to git too.
"""

import json
from pathlib import Path

ROOT = Path(__file__).parent.parent
VER_JSON = ROOT / "version.json"
OUT      = ROOT / "core" / "_version.py"

def main():
    data = json.loads(VER_JSON.read_text(encoding="utf-8"))
    version = data.get("version", "0.0.0")
    OUT.write_text(
        f'"""Generated by tools/embed_version.py — do NOT edit by hand."""\n'
        f'VERSION = "{version}"\n',
        encoding="utf-8",
    )
    print(f"[embed_version] {OUT} -> {version}")

if __name__ == "__main__":
    main()
