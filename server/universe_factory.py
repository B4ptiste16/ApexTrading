"""
APEX server-side UNIVERSE FACTORY  (V4.6.73)
─────────────────────────────────────────────────────────────────
Generates a set of THEMED public universes on the Oracle server, NOT tied to
any user account. Bots (created in Make Bot) reference one of these by name, or
ship their own custom universe. Regenerated weekly (Monday at the US market
open) by the auto-scheduler.

Each universe is written in the SAME format the Universe tab uses:
    TICKER    # score=NN.N | <one-line reason>
so the desktop can read/display them like any other universe.

Themes:
    long_term     — durable momentum, lower volatility (buy-and-hold)
    short         — weakest momentum (short candidates)
    short_term    — most active / high churn (intraday & swing)
    speculative   — highest volatility (high risk / high reward)
    crypto        — major coins
    options       — liquid, high-volatility optionable names

Scoring uses 3-month daily bars from yfinance (free, no account). Best-effort:
a ticker that can't be priced is skipped; a theme with no data keeps its
previous file.
"""

from __future__ import annotations

import os
