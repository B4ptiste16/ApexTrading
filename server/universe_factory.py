    "LRCX", "ASML", "TSM", "MRVL", "ON", "WDC", "STX", "JPM", "BAC", "GS", "MS",
    "V", "MA", "AXP", "BRK-B", "UNH", "LLY", "JNJ", "PFE", "MRK", "ABBV", "XOM",
    "CVX", "COP", "WMT", "COST", "HD", "NKE", "MCD", "SBUX", "DIS", "BA", "CAT",
